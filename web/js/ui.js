const SVG_NS = 'http://www.w3.org/2000/svg';
export function icon(name) {
  const s = document.createElementNS(SVG_NS, 'svg');
  s.setAttribute('viewBox', '0 0 24 24');
  s.setAttribute('aria-hidden', 'true');
  s.setAttribute('focusable', 'false');
  s.classList.add('icon', `icon-${name}`);
  s.innerHTML = ICONS[name] || '';
  return s;
}

// ---- toast: one at a time, bottom-centre above the sheet, announced politely ----
let toastTimer = 0;
let toastHost = null;
export function toast(text, opts = {}) {
  toastHost ||= document.getElementById('toasts') || document.body.appendChild(h('div', { id: 'toasts', class: 'toast-host', 'aria-live': 'polite', 'aria-atomic': 'true', role: 'status' }));
  clearTimeout(toastTimer);
  const { action } = opts;
  const el = h('div', { class: 'toast' }, h('span', { class: 'toast-text' }, text));
  const dismiss = () => {
    clearTimeout(toastTimer);
    if (el.parentNode !== toastHost) return;
    el.classList.remove('show');
    setTimeout(() => el.remove(), 200);
  };
  if (action) {
    el.append(h('button', { type: 'button', class: 'toast-action', onclick: () => { dismiss(); action.onClick?.(); } }, action.label));
  }
  toastHost.replaceChildren(el);
  requestAnimationFrame(() => el.classList.add('show'));
  toastTimer = setTimeout(dismiss, opts.ms ?? (action ? 7000 : 4000));
  return dismiss;
}

export function lineBadge(line) {
  const el = h('span', { class: 'badge' }, String(line?.code ?? ''));
  el.style.background = line?.color || '#757575';
  el.style.color = line?.textColor || '#fff';
  return el;
}

